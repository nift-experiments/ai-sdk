import {build} from 'esbuild';
import {readFile,writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import path from 'node:path';
import React from 'react';
import {renderToString} from 'react-dom/server';
import {chromeBuildOptions} from './chrome-build-options.mjs';
const root=process.cwd();
const result=await build({entryPoints:['ui/docs-chrome.tsx'],outfile:'generated/docs-chrome.cjs',bundle:true,platform:'node',format:'cjs',external:['react','react/*','react-dom','react-dom/*'],metafile:true,...chromeBuildOptions(root)});
const next=Object.keys(result.metafile.inputs).filter(file=>/node_modules\/next\//.test(file));
if(next.length)throw Error('Unexpected Next runtime: '+next.join(','));
const {DocsChrome}=createRequire(import.meta.url)(path.join(root,'generated/docs-chrome.cjs'));
const tree=JSON.parse(await readFile('generated/current-docs-navigation.json','utf8'));
let article='<article id="nd-page"><h1>Navigation probe</h1><p>Static article slot.</p></article>';
if(process.argv.includes('--fixture'))article=await readFile('generated/chrome-fixture-article.html','utf8');
const html=renderToString(React.createElement(DocsChrome,{route:'/docs/introduction',tree,versionPaths:{},article}),{identifierPrefix:'chrome-'});
await writeFile('generated/docs-chrome-probe.html',html);
await writeFile('generated/docs-chrome-metafile.json',JSON.stringify(result.metafile,null,2));
console.log(JSON.stringify({nextRuntimeInputs:next.length,htmlBytes:Buffer.byteLength(html)}));
