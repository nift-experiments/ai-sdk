import {build} from 'esbuild';
import {chromeBuildOptions} from './chrome-build-options.mjs';
import {createRequire} from 'node:module';
import {renderToReadableStream} from 'react-dom/server';
import path from 'node:path';
import {writeFile} from 'node:fs/promises';
const result=await build({entryPoints:['ui/page-shell-probe.tsx'],outfile:'generated/page-shell-probe.cjs',bundle:true,platform:'node',format:'cjs',external:['react','react/*','react-dom','react-dom/*'],metafile:true,...chromeBuildOptions(process.cwd())});
const next=Object.keys(result.metafile.inputs).filter(file=>/node_modules\/next\//.test(file));
if(next.length)throw Error('Unexpected Next runtime: '+next.join(','));
const {pageShellProbe}=createRequire(import.meta.url)(path.resolve('generated/page-shell-probe.cjs'));
const element=pageShellProbe({route:'/docs/introduction',files:[{type:'page',path:'introduction.mdx',data:{title:'Probe',toc:[],description:'Probe'}}]});
const stream=await renderToReadableStream(element);
await stream.allReady;
const html=await new Response(stream).text();
await writeFile('generated/page-shell-probe.html',html);
const report={htmlBytes:Buffer.byteLength(html),rawBodySlots:(html.match(/data-ai-raw-body-slot/g)||[]).length,nextRuntimeInputs:next.length};
if(report.rawBodySlots!==1)throw Error('Raw body slot ownership failed');
await writeFile('generated/page-shell-probe-report.json',JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report));
